'use strict';
// Generates syntaxes/smartmotor.tmLanguage.json from src/commands.json.
// Usage: node scripts/build-grammar.js [--check]
const fs = require('fs');
const path = require('path');
const { commands } = require('../src/commands.json');

const OUTPUT = path.join(__dirname, '..', 'syntaxes', 'smartmotor.tmLanguage.json');

const escape = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

// Alternation of command names, longest first; numbered ones take digits (SADDR2, PID1, BAUD9600).
function words(kinds) {
  const names = new Map();
  for (const c of commands) {
    if (!kinds.includes(c.kind) || !/^[A-Z]/.test(c.name)) continue;
    const pattern = escape(c.name) + (c.numbered ? '\\d*' : '');
    names.set(pattern, c.name.length);
  }
  return [...names.keys()].sort((a, b) => names.get(b) - names.get(a) || a.localeCompare(b)).join('|');
}

const reportable = [...new Set(commands.filter((c) => c.report && /^[A-Z]/.test(c.name)).map((c) => c.name))]
  .sort((a, b) => b.length - a.length || a.localeCompare(b)).map(escape).join('|');

// '?' in RUN? is not a word character, so control words end with a lookahead instead of \b.
const END = '(?![A-Za-z0-9_?])';

function grammar() {
  return {
    $schema: 'https://raw.githubusercontent.com/martinring/tmlanguage/master/tmlanguage.json',
    name: 'SmartMotor BASIC',
    scopeName: 'source.smartmotor',
    comment: 'Generated by scripts/build-grammar.js from src/commands.json. Do not edit by hand.',
    fileTypes: ['sms'],
    patterns: [
      { include: '#comment' },
      { include: '#directive' },
      { include: '#statement' },
    ],
    repository: {
      comment: {
        name: 'comment.line.apostrophe.smartmotor',
        match: "(').*$",
        captures: { 1: { name: 'punctuation.definition.comment.smartmotor' } },
      },
      directive: {
        comment: 'SMI preprocessor: #define NAME value, #ifdef NAME ... #endif',
        patterns: [
          {
            match: '^\\s*(#define)\\s+(\\S+)',
            captures: {
              1: { name: 'keyword.control.directive.smartmotor' },
              2: { name: 'entity.name.constant.smartmotor' },
            },
          },
          {
            match: '^\\s*(#(?:ifdef|ifndef|if|elif|else|endif|undef|include))\\b\\s*([A-Za-z_][A-Za-z0-9_]*)?',
            captures: {
              1: { name: 'keyword.control.directive.smartmotor' },
              2: { name: 'entity.name.constant.smartmotor' },
            },
          },
        ],
      },
      statement: {
        patterns: [
          { include: '#string' },
          { include: '#label' },
          { include: '#call' },
          { include: '#control' },
          { include: '#character' },
          { include: '#flag' },
          { include: '#reset' },
          { include: '#command' },
          { include: '#register' },
          { include: '#function' },
          { include: '#report' },
          { include: '#array' },
          { include: '#user-variable' },
          { include: '#number' },
          { include: '#address' },
          { include: '#operator' },
          { include: '#punctuation' },
        ],
      },
      string: {
        name: 'string.quoted.double.smartmotor',
        begin: '"',
        end: '"|$',
        beginCaptures: { 0: { name: 'punctuation.definition.string.begin.smartmotor' } },
        endCaptures: { 0: { name: 'punctuation.definition.string.end.smartmotor' } },
      },
      label: {
        comment: 'Label C0, C1, ... C999 alone on its line (a comment may follow)',
        match: "^\\s*(C\\d+)(?=\\s*(?:'|$))",
        captures: { 1: { name: 'entity.name.function.label.smartmotor' } },
      },
      call: {
        comment: 'GOSUB4, GOSUB(4), GOTO10, GOTO(10), GOSUB(x)',
        patterns: [
          {
            match: '\\b(GOSUB|GOTO)(?:(\\d+)\\b|\\s*(\\()\\s*(\\d+)\\s*(\\)))',
            captures: {
              1: { name: 'keyword.control.call.smartmotor' },
              2: { name: 'entity.name.function.label.smartmotor' },
              3: { name: 'punctuation.section.brackets.smartmotor' },
              4: { name: 'entity.name.function.label.smartmotor' },
              5: { name: 'punctuation.section.brackets.smartmotor' },
            },
          },
          { match: '\\b(?:GOSUB|GOTO)\\b', name: 'keyword.control.call.smartmotor' },
        ],
      },
      control: {
        match: `\\b(?:${words(['control'])})${END}`,
        name: 'keyword.control.smartmotor',
      },
      character: {
        comment: 'Character code in PRINT: #13, or a variable holding it: #a',
        match: '#(?:\\d+|([a-z])\\1{0,2})\\b',
        name: 'constant.character.smartmotor',
      },
      report: {
        comment: 'Report commands: RPA, RKP, RBa, RW(0), Ra, Raa, Rab[3]',
        match: `\\bR(?:${reportable}|([a-z])\\1{0,2}|ab|af|al|aw)(?![A-Za-z0-9_])`,
        name: 'support.function.report.smartmotor',
      },
      flag: {
        comment: 'Status bits: Bo, Bt, Ba, Bls, Bi(0), B(word,bit)',
        match: `\\b(?:${words(['flag'])})\\b`,
        name: 'constant.language.flag.smartmotor',
      },
      reset: {
        comment: 'Flag resets: ZS, Za, Zrs, Z(word,bit)',
        match: `\\b(?:${words(['reset'])})\\b`,
        name: 'keyword.other.reset.smartmotor',
      },
      command: {
        match: `\\b(?:${words(['command'])})\\b`,
        name: 'keyword.other.command.smartmotor',
      },
      register: {
        match: `\\b(?:${words(['register'])})\\b`,
        name: 'variable.language.register.smartmotor',
      },
      function: {
        match: `\\b(?:${words(['function'])})\\b`,
        name: 'support.function.smartmotor',
      },
      array: {
        comment: 'User arrays: ab[] (8 bit), aw[] (16 bit), al[] (32 bit), af[] (float)',
        match: '\\b(?:ab|aw|al|af)(?=\\s*\\[)',
        name: 'variable.other.array.smartmotor',
      },
      'user-variable': {
        comment: 'User variables: a..z, aa..zz, aaa..zzz (the same letter repeated)',
        match: '\\b([a-z])\\1{0,2}\\b',
        name: 'variable.other.user.smartmotor',
      },
      number: {
        match: '\\b\\d+(?:\\.\\d+)?\\b',
        name: 'constant.numeric.smartmotor',
      },
      address: {
        comment: 'Combitronic motor address: G:0, EA:2, B(0,2):2',
        match: ':(?=\\s*(?:\\d|[a-z]))',
        name: 'punctuation.separator.address.smartmotor',
      },
      operator: {
        patterns: [
          { match: '==|!=|<=|>=|<|>', name: 'keyword.operator.comparison.smartmotor' },
          { match: '&|\\||!|\\^', name: 'keyword.operator.logical.smartmotor' },
          { match: '=', name: 'keyword.operator.assignment.smartmotor' },
          { match: '\\+|-|\\*|/|%', name: 'keyword.operator.arithmetic.smartmotor' },
        ],
      },
      punctuation: {
        patterns: [
          { match: ',', name: 'punctuation.separator.comma.smartmotor' },
          { match: '[()\\[\\]]', name: 'punctuation.section.brackets.smartmotor' },
        ],
      },
    },
  };
}

const text = JSON.stringify(grammar(), null, 2) + '\n';
if (require.main === module) {
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(OUTPUT, 'utf8') !== text) {
      console.error('syntaxes/smartmotor.tmLanguage.json is out of date: run npm run build:grammar');
      process.exit(1);
    }
  } else {
    fs.writeFileSync(OUTPUT, text);
  }
}

module.exports = { grammar, text };
